"""PostgreSQL dialect."""

from typing import Any, cast, override

from ..queries import IsExists, Reflect
from ..structures import (
    BinaryColumn,
    BooleanColumn,
    CharStringColumn,
    Database,
    DateColumn,
    DatetimeColumn,
    DecimalColumn,
    FloatColumn,
    Index,
    IntegerColumn,
    Schema,
    Table,
    TextColumn,
)
from .i_dialect import IDialect

_int_name_dict = {
    1: "smallint",
    2: "smallint",
    4: "integer",
    8: "bigint",
}


class PostgreSql(IDialect):
    """Dialect of PostgreSQL.

    A table is qualified with its schema only: PostgreSQL cannot refer to a
    table of another database.
    """

    def __init__(self) -> None:
        super().__init__(dialect_name="postgresql")

    @property
    @override
    def placeholder(self) -> str:
        return "%s"

    @override
    def get_table_qualifier(self, table: Table) -> str:
        q_ar = []

        if table.schema:
            q_ar.append(table.schema.schema_name)

        q_ar.append(table.table_name)

        return ".".join(self.quote_identifier(x) for x in q_ar)

    @override
    def _get_boolean_string(self, val: bool) -> str:
        return "TRUE" if val else "FALSE"

    @override
    def _get_binary_string(self, val: bytes) -> str:
        return "'\\x" + val.hex() + "'"

    @override
    def _get_identity_string(self) -> str:
        return "GENERATED BY DEFAULT AS IDENTITY"

    @override
    def get_BinaryColumn_declaration(self, column: BinaryColumn) -> str:
        return self._get_declaration_string(column, type_string="bytea")

    @override
    def get_BooleanColumn_declaration(self, column: BooleanColumn) -> str:
        return self._get_declaration_string(column, type_string="boolean")

    @override
    def get_CharStringColumn_declaration(self, column: CharStringColumn) -> str:
        type_string = f"char({column.size})" if column.is_fixed else f"varchar({column.size})"

        return self._get_declaration_string(column, type_string)

    @override
    def get_DateColumn_declaration(self, column: DateColumn) -> str:
        return self._get_declaration_string(column, type_string="date")

    @override
    def get_DatetimeColumn_declaration(self, column: DatetimeColumn) -> str:
        return self._get_declaration_string(column, type_string="timestamp")

    @override
    def get_DecimalColumn_declaration(self, column: DecimalColumn) -> str:
        return self._get_declaration_string(
            column, type_string=f"numeric({column.precision}, {column.scale})"
        )

    @override
    def get_FloatColumn_declaration(self, column: FloatColumn) -> str:
        return self._get_declaration_string(
            column, type_string="double precision" if column.is_double else "real"
        )

    @override
    def get_IntegerColumn_declaration(self, column: IntegerColumn) -> str:
        return self._get_declaration_string(column, type_string=_int_name_dict[column.n_bytes])

    @override
    def get_TextColumn_declaration(self, column: TextColumn) -> str:
        return self._get_declaration_string(column, type_string="text")

    @override
    def get_IsExists_database_string(
        self, query: IsExists, parameters: list[Any] | None = None
    ) -> str:
        database = cast(Database, query.structure)

        name = self.get_literal_string(database.database_name)
        return f"SELECT COUNT(*) FROM pg_database WHERE datname={name}"

    @override
    def get_IsExists_schema_string(
        self, query: IsExists, parameters: list[Any] | None = None
    ) -> str:
        schema = cast(Schema, query.structure)

        name = self.get_literal_string(schema.schema_name)
        return f"SELECT COUNT(*) FROM information_schema.schemata WHERE schema_name={name}"

    @override
    def get_IsExists_table_string(
        self, query: IsExists, parameters: list[Any] | None = None
    ) -> str:
        table = cast(Table, query.structure)

        return "SELECT COUNT(*) FROM information_schema.tables WHERE table_name={}{}".format(
            self.get_literal_string(table.table_name),
            self._get_schema_filter("table_schema", table),
        )

    @override
    def get_IsExists_index_string(
        self, query: IsExists, parameters: list[Any] | None = None
    ) -> str:
        index = cast(Index, query.structure)

        return "SELECT COUNT(*) FROM pg_indexes WHERE indexname={}{}".format(
            self.get_literal_string(index.index_name),
            self._get_schema_filter("schemaname", index.table),
        )

    def _get_schema_filter(self, column_name: str, table: Table) -> str:
        if table.schema:
            return f" AND {column_name}={self.get_literal_string(table.schema.schema_name)}"

        return f" AND {column_name}=current_schema()"

    @override
    def get_Reflect_table_string(self, query: Reflect, parameters: list[Any] | None = None) -> str:
        table = query.structure

        return self._get_information_schema_string(
            table,
            schema_string=(
                self.get_literal_string(table.schema.schema_name)
                if table.schema
                else "current_schema()"
            ),
            identity_string="CASE WHEN c.is_identity = 'YES' THEN 1 ELSE 0 END",
        )

    @override
    def _get_reflected_type(
        self,
        data_type: str,
        size: int | None,
        precision: int | None,
        column_type: str | None,
    ) -> dict[str, Any]:
        if data_type in ("character varying", "character"):
            if size is None:
                return {"kind": "text"}

            return {"kind": "char", "is_fixed": data_type == "character", "size": size}

        if data_type == "text":
            return {"kind": "text"}

        if data_type in ("smallint", "integer", "bigint"):
            return {
                "kind": "integer",
                "n_bytes": {"smallint": 2, "integer": 4, "bigint": 8}[data_type],
            }

        if data_type in ("double precision", "real"):
            return {"kind": "float", "is_double": data_type == "double precision"}

        if data_type.startswith("timestamp"):
            return {"kind": "datetime"}

        if data_type == "date":
            return {"kind": "date"}

        if data_type == "boolean":
            return {"kind": "boolean"}

        if data_type == "numeric":
            return {"kind": "decimal", "precision": precision}

        if data_type == "bytea":
            return {"kind": "binary"}

        return super()._get_reflected_type(data_type, size, precision, column_type)
